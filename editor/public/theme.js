// Shared between the editor server (Node) and the editor UI (browser):
// the curated font list and the function that turns Site Styles settings
// into the CSS written to assets/css/theme.css.
(function (root) {
  var FONTS = [
    { name: "System (default)", css: "", google: null },
    { name: "Inter", css: '"Inter", sans-serif', google: "Inter:ital,wght@0,300..700;1,300..700" },
    { name: "DM Sans", css: '"DM Sans", sans-serif', google: "DM+Sans:ital,wght@0,300..700;1,300..700" },
    { name: "Work Sans", css: '"Work Sans", sans-serif', google: "Work+Sans:ital,wght@0,300..700;1,300..700" },
    { name: "Space Grotesk", css: '"Space Grotesk", sans-serif', google: "Space+Grotesk:wght@300..700" },
    { name: "Syne", css: '"Syne", sans-serif', google: "Syne:wght@400..800" },
    { name: "Archivo", css: '"Archivo", sans-serif', google: "Archivo:ital,wght@0,300..700;1,300..700" },
    { name: "EB Garamond", css: '"EB Garamond", serif', google: "EB+Garamond:ital,wght@0,400..700;1,400..700" },
    { name: "Cormorant Garamond", css: '"Cormorant Garamond", serif', google: "Cormorant+Garamond:ital,wght@0,300..700;1,300..700" },
    { name: "Playfair Display", css: '"Playfair Display", serif', google: "Playfair+Display:ital,wght@0,400..800;1,400..800" },
    { name: "Libre Baskerville", css: '"Libre Baskerville", serif', google: "Libre+Baskerville:ital,wght@0,400;0,700;1,400" },
    { name: "Fraunces", css: '"Fraunces", serif', google: "Fraunces:ital,wght@0,300..700;1,300..700" },
    { name: "IBM Plex Mono", css: '"IBM Plex Mono", monospace', google: "IBM+Plex+Mono:ital,wght@0,300;0,400;0,600;1,400" },
    { name: "Space Mono", css: '"Space Mono", monospace', google: "Space+Mono:ital,wght@0,400;0,700;1,400" },
  ];

  var DEFAULTS = {
    headingFont: "System (default)",
    bodyFont: "System (default)",
    baseSize: 16,
    headingWeight: "400",
    textColor: "#111111",
    backgroundColor: "#ffffff",
  };

  function fontByName(name) {
    for (var i = 0; i < FONTS.length; i++) if (FONTS[i].name === name) return FONTS[i];
    return FONTS[0];
  }

  function googleUrl(fontNames) {
    var fams = [];
    fontNames.forEach(function (n) {
      var f = fontByName(n);
      if (f.google && fams.indexOf(f.google) === -1) fams.push(f.google);
    });
    if (!fams.length) return null;
    return "https://fonts.googleapis.com/css2?family=" + fams.join("&family=") + "&display=swap";
  }

  // Every curated font whose family name appears in the given HTML
  // (from text the editor styled with a specific font).
  function fontsUsedIn(html) {
    var decls = [];
    var re = /font-family:\s*([^;>]+)/gi;
    var m;
    while ((m = re.exec(html)) !== null) decls.push(m[1].replace(/&quot;/g, '"'));
    var used = [];
    FONTS.forEach(function (f) {
      if (!f.google) return;
      var quoted = '"' + f.name + '"';
      if (decls.some(function (d) { return d.indexOf(quoted) !== -1; })) used.push(f.name);
    });
    return used;
  }

  function buildThemeCss(settings, extraFonts) {
    var s = {};
    Object.keys(DEFAULTS).forEach(function (k) {
      s[k] = settings && settings[k] != null && settings[k] !== "" ? settings[k] : DEFAULTS[k];
    });
    var heading = fontByName(s.headingFont);
    var body = fontByName(s.bodyFont);
    var load = [s.headingFont, s.bodyFont].concat(extraFonts || []);
    var url = googleUrl(load);

    var out = [];
    out.push("/* Generated by the site editor (Site Styles panel). Changes made here by hand will be overwritten. */");
    out.push("/* theme-settings: " + JSON.stringify(s) + " */");
    if (url) out.push('@import url("' + url + '");');
    out.push("");
    if (Number(s.baseSize) !== 16) {
      out.push("html { font-size: " + (Number(s.baseSize) / 16 * 100).toFixed(2) + "%; }");
    }
    var bodyRules = [];
    if (body.css) bodyRules.push("font-family: " + body.css + ";");
    if (s.textColor.toLowerCase() !== DEFAULTS.textColor) bodyRules.push("color: " + s.textColor + ";");
    if (s.backgroundColor.toLowerCase() !== DEFAULTS.backgroundColor) bodyRules.push("background: " + s.backgroundColor + ";");
    if (bodyRules.length) out.push("body { " + bodyRules.join(" ") + " }");
    if (s.backgroundColor.toLowerCase() !== DEFAULTS.backgroundColor) {
      out.push(".site-header, .dropdown-menu { background: " + s.backgroundColor + "; }");
    }
    var headRules = [];
    if (heading.css) headRules.push("font-family: " + heading.css + ";");
    if (String(s.headingWeight) !== DEFAULTS.headingWeight) headRules.push("font-weight: " + s.headingWeight + ";");
    if (headRules.length) out.push("h1, h2, h3, h4, .logo { " + headRules.join(" ") + " }");
    return out.join("\n") + "\n";
  }

  function parseThemeSettings(css) {
    var m = css && css.match(/\/\* theme-settings: (\{.*\}) \*\//);
    if (!m) return Object.assign({}, DEFAULTS);
    try { return Object.assign({}, DEFAULTS, JSON.parse(m[1])); } catch (e) { return Object.assign({}, DEFAULTS); }
  }

  var api = {
    FONTS: FONTS,
    DEFAULTS: DEFAULTS,
    fontByName: fontByName,
    googleUrl: googleUrl,
    fontsUsedIn: fontsUsedIn,
    buildThemeCss: buildThemeCss,
    parseThemeSettings: parseThemeSettings,
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.SiteTheme = api;
})(this);
